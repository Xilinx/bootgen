extern "C" void LmsLogTrace(const char* format, ...)
{
    if (GET_LOG_LEVEL() < LogLevel::TRACE)
    {
        return;
    }

    char buffer[1024];
    va_list args;
    va_start(args, format);
    vsnprintf(buffer, sizeof(buffer), format, args);
    va_end(args);

    LOG_TRACE("%s", buffer);
}
